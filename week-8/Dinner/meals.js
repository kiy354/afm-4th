  // '돼지고기 앞다리살 200g' → '돼지고기 앞다리살', '무 1/4개 (나박썰기)' → '무'
  function ingredientName(raw) {
    let s = raw.replace(/\([^)]*\)|\[[^\]]*\]/g, ' ');
    s = s.split(' 또는 ')[0].split(' + ')[0];
    const words = [];
    for (const w of s.trim().split(/\s+/)) {
      if (/^[0-9]/.test(w) || QTY_WORDS.includes(w)) break;
      words.push(w);
    }
    return words.join(' ');
  }

